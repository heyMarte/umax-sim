CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 role VARCHAR(16) NOT NULL,
 active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS sessions (
 token CHAR(64) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 csrf CHAR(64) NOT NULL, expires DOUBLE NOT NULL, INDEX(expires)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS devices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL, token CHAR(64) NOT NULL UNIQUE,
 revoked TINYINT NOT NULL DEFAULT 0, heartbeat DOUBLE NULL,
 subscriptions TEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sims (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 phone VARCHAR(32) NOT NULL UNIQUE, carrier VARCHAR(16) NOT NULL,
 location VARCHAR(50) NOT NULL, shop VARCHAR(200) NOT NULL,
 threshold DECIMAL(12,2) NOT NULL DEFAULT 20,
 balance DECIMAL(12,2) NULL, checked_at DOUBLE NULL,
 package_expires DATE NULL, preservation_status VARCHAR(200) NULL,
 next_check DATE NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS bindings (
 device_id BIGINT UNSIGNED NOT NULL, subscription_id INT NOT NULL,
 sim_id BIGINT UNSIGNED NOT NULL UNIQUE,
 version CHAR(48) NOT NULL,
 PRIMARY KEY(device_id,subscription_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 device_id BIGINT UNSIGNED NOT NULL,
 event_id VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 sim_id BIGINT UNSIGNED NULL, subscription_id INT NULL,
 sender VARCHAR(200) NOT NULL, body MEDIUMTEXT NOT NULL,
 received_at DOUBLE NOT NULL, uploaded_at DOUBLE NOT NULL,
 UNIQUE KEY device_event(device_id,event_id), INDEX(uploaded_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS records (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 sim_id BIGINT UNSIGNED NOT NULL, kind VARCHAR(16) NOT NULL,
 amount DECIMAL(12,2) NOT NULL, at DOUBLE NOT NULL, note VARCHAR(500) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor VARCHAR(100) NOT NULL, action VARCHAR(50) NOT NULL,
 object_id VARCHAR(200) NOT NULL, at DOUBLE NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS attempts (
 ip VARCHAR(64) PRIMARY KEY, count INT NOT NULL, since DOUBLE NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
